#!/usr/bin/env python3
"""Generates src/components/icons/plannerCheckboxIcons.h (Planner to-do checkboxes).

Material Design checkbox proportions (18 px box in a 24 px icon, 2 px stroke,
rounded corners, checked = filled box with a light check mark), with a thicker
stroke so the outline stays crisp on 1-bit e-ink. Output uses the FreeInkUI
Mask1 layout of the other list icons: row-major, MSB first, 0 = ink.

Requires Pillow. Usage: python3 scripts/generate_planner_checkbox_icons.py
"""

from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src/components/icons/plannerCheckboxIcons.h"
SS = 8  # supersampling factor


def render(size: int, checked: bool) -> Image.Image:
    s = size * SS
    img = Image.new("L", (s, s), 255)
    d = ImageDraw.Draw(img)
    margin = size * 4 // 32
    box = (margin * SS, margin * SS, (size - margin) * SS - 1, (size - margin) * SS - 1)
    radius = max(2, size // 8) * SS
    stroke = max(2, round(size * 3 / 32)) * SS
    if checked:
        d.rounded_rectangle(box, radius=radius, fill=0)
        # Check mark, in the box's coordinate frame (Material: short arm then long arm).
        x0, y0, x1, y1 = box
        w = x1 - x0
        pts = [(x0 + w * 0.22, y0 + w * 0.52), (x0 + w * 0.42, y0 + w * 0.72), (x0 + w * 0.79, y0 + w * 0.30)]
        d.line(pts, fill=255, width=stroke, joint="curve")
        for p in (pts[0], pts[2]):
            r = stroke / 2
            d.ellipse((p[0] - r, p[1] - r, p[0] + r, p[1] + r), fill=255)
    else:
        d.rounded_rectangle(box, radius=radius, outline=0, width=stroke)
    return img.resize((size, size), Image.LANCZOS).point(lambda v: 0 if v < 128 else 255)


def to_mask1(img: Image.Image) -> list[int]:
    w, h = img.size
    px = img.load()
    out = []
    for y in range(h):
        for bx in range(0, w, 8):
            byte = 0
            for bit in range(8):
                x = bx + bit
                ink = x < w and px[x, y] == 0
                byte |= (0 if ink else 1) << (7 - bit)
            out.append(byte)
    return out


def emit(name: str, size: int, data: list[int]) -> str:
    rows = []
    for i in range(0, len(data), 18):
        rows.append("    " + ", ".join(f"0x{b:02X}" for b in data[i : i + 18]))
    body = ",\n".join(rows)
    return (
        f"static const uint8_t {name}_bits[] = {{\n{body}}};\n"
        f"static const freeink::Icon {name} = {{{size}, {size}, {size // 2}, {name}_bits}};\n"
    )


def main() -> None:
    parts = [
        "#pragma once\n",
        "// Generated by scripts/generate_planner_checkbox_icons.py. Do not edit by hand.\n",
        '#include <cstdint>\n\n#include "Icon.h"\n\n',
    ]
    for size in (24, 32):
        for checked in (False, True):
            name = f"icon_planner_checkbox_{'checked' if checked else 'empty'}_{size}"
            parts.append(emit(name, size, to_mask1(render(size, checked))))
    OUT.write_text("".join(parts))
    print(f"wrote {OUT.relative_to(ROOT)}")
    # ASCII preview for review
    for checked in (False, True):
        img = render(32, checked)
        print("\n".join("".join("#" if img.getpixel((x, y)) == 0 else "." for x in range(32)) for y in range(32)))
        print()


if __name__ == "__main__":
    main()
